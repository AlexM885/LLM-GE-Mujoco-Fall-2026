"""Write (and optionally submit) one island-controller job per (preset, seed).

    python scripts/uqd_sweep.py --presets controlled_baseline,controlled_archive_sampling \\
        --seeds 0,1,2 --sweep-dir mujoco_rl_output/uqd_sweeps/pilot            # dry run
    python scripts/uqd_sweep.py ... --submit                                   # sbatch them

Each job exports MUJOCO_UQD_PRESET, MUJOCO_RUN_SEED, MUJOCO_UQD_RUN_DIR and a
private island-script path, then runs islands_wrapper.py exactly as
island_controller.sbatch does; everything else about the run (generations,
population, training budget, LLM) comes from src/cfg/constants_Mujoco.py and
is identical across the sweep. The LLM server must already be running
(server.sh), as for any island run.

For each run a post_<preset>_seed<R>.sh is also written: the held-out final
evaluation (and ARIA when the preset enables it), to be submitted after the
search has finished. Nothing is submitted without --submit.

The default preset list is the recommended pilot: the legacy baseline, the
controlled reference, and one controlled ablation per mechanism (fixed
sampling, archive re-evaluation, adaptive sampling, depth with random
replacement) plus the ARIA combination. Avoid crossing every option.
"""

import argparse
import os
import shlex
import subprocess
import sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO_ROOT)

from src.cfg.uqd_presets import PRESETS, resolve_uqd_config  # noqa: E402

DEFAULT_PRESETS = ("legacy_baseline,controlled_baseline,controlled_me_sampling_n32,"
                   "controlled_archive_sampling,controlled_parallel_adaptive_sampling,"
                   "controlled_deep_grid_sampling_n10,controlled_archive_sampling_aria")

CONTROLLER = """#!/bin/bash
#SBATCH --job-name=uqd_{tag}
#SBATCH -N1 --ntasks-per-node=4
#SBATCH --mem=16G
#SBATCH --time=8:00:00
#SBATCH --output={sweep_dir}/logs/controller_{tag}-%j.out
# Generated by scripts/uqd_sweep.py
cd {repo}
module load cuda
export HF_HOME=/storage/ice-shared/vip-vvk/llm_storage/
export MUJOCO_UQD_PRESET={preset}
export MUJOCO_RUN_SEED={seed}
export MUJOCO_UQD_RUN_DIR={run_dir}
export LLMGE_ISLAND_TEMP_SCRIPT={sweep_dir}/islands/{tag}_island_{{ISLAND_NUM}}.sh
{overrides}uv run python islands_wrapper.py {checkpoints} --num_islands 1 --llms {llms} --prompt_groups "{prompts}"
"""

POST = """#!/bin/bash
#SBATCH --job-name=uqdpost_{tag}
#SBATCH -t 8:00:00
#SBATCH -c 4
#SBATCH --mem 8G
#SBATCH -N 1
#SBATCH --output={sweep_dir}/logs/post_{tag}-%j.out
# Generated by scripts/uqd_sweep.py. Submit after the search has finished.
cd {repo}
module load uv
unset VIRTUAL_ENV
{export_step}uv run --isolated --project sota/MujocoRL/eval_env python scripts/uqd_final_eval.py --run-dir {run_dir} --slurm
{aria_step}"""


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--presets", default=DEFAULT_PRESETS)
    parser.add_argument("--seeds", default="0,1,2,3,4")
    parser.add_argument("--sweep-dir", required=True)
    parser.add_argument("--overrides", default="", help="JSON applied to every preset (relabels as exp_)")
    parser.add_argument("--llms", default="llama3")
    parser.add_argument("--prompt-groups", default="Mujoco/Normal")
    parser.add_argument("--submit", action="store_true")
    args = parser.parse_args()

    presets = [p.strip() for p in args.presets.split(",") if p.strip()]
    seeds = [int(s) for s in args.seeds.split(",") if s.strip()]
    sweep_dir = os.path.abspath(args.sweep_dir)
    for sub in ("logs", "islands", "jobs"):
        os.makedirs(os.path.join(sweep_dir, sub), exist_ok=True)

    scripts = []
    for preset in presets:
        if preset not in PRESETS:
            raise SystemExit(f"unknown preset {preset}")
        cfg = resolve_uqd_config(preset, args.overrides, population_size=32)   # validate now
        for seed in seeds:
            tag = f"{cfg['name']}_seed{seed}"
            run_dir = os.path.join(sweep_dir, "runs", tag)
            checkpoints = os.path.join(sweep_dir, "checkpoints", tag)
            overrides = (f"export MUJOCO_UQD_OVERRIDES={shlex.quote(args.overrides)}\n"
                         if args.overrides else "")
            if preset == "legacy_baseline":
                # The legacy path is unseeded except for training; MUJOCO_EVAL_SEED
                # carries the replicate so replicates differ in training noise.
                overrides += f"export MUJOCO_EVAL_SEED={seed}\n"
            body = CONTROLLER.format(tag=tag, sweep_dir=sweep_dir, repo=REPO_ROOT, preset=preset, seed=seed,
                                     run_dir=run_dir, checkpoints=checkpoints, llms=args.llms,
                                     prompts=args.prompt_groups, overrides=overrides)
            path = os.path.join(sweep_dir, "jobs", f"run_{tag}.sbatch")
            with open(path, "w", encoding="utf-8") as f:
                f.write(body)
            export_step = ""
            if preset == "legacy_baseline":
                export_step = (
                    "# Legacy runs: export the last checkpoint first (fill in the generation).\n"
                    f"# uv run --isolated --project sota/MujocoRL/eval_env --with deap python "
                    f"scripts/uqd_export_legacy_archive.py --seed {seed} --out-dir {run_dir} \\\n"
                    f"#   --checkpoint {checkpoints}/island_<llm>_<prompts>/checkpoint_gen_<N>.pkl "
                    f"--global-data {checkpoints}/global_data/global_gen_<N>.pkl\n")
            aria_step = ""
            if cfg["aria"]["enabled"]:
                aria_step = (f"uv run --isolated --project sota/MujocoRL/eval_env python scripts/uqd_aria.py "
                             f"--run-dir {run_dir} --slurm\n")
            post = POST.format(tag=tag, sweep_dir=sweep_dir, repo=REPO_ROOT, run_dir=run_dir,
                               export_step=export_step, aria_step=aria_step)
            with open(os.path.join(sweep_dir, "jobs", f"post_{tag}.sh"), "w", encoding="utf-8") as f:
                f.write(post)
            scripts.append(path)

    print(f"wrote {len(scripts)} controller jobs to {sweep_dir}/jobs")
    for path in scripts:
        if args.submit:
            out = subprocess.run(["sbatch", path], capture_output=True, text=True)
            print(path, out.stdout.strip() or out.stderr.strip())
        else:
            print("  (dry run)", path)


if __name__ == "__main__":
    main()
