"""Small end-to-end uncertain-QD run on real MuJoCo, without the LLM.

This checks the plumbing (config, seeds, training jobs, per-episode samples,
re-evaluation, archive strategies, logging, held-out evaluation and ARIA) on
tiny budgets. It is NOT an experiment: offspring come from a seeded random
hyperparameter mutation of sota/MujocoRL/network.py (hidden sizes, learning
rate, exploration noise), not from the LLM, and training runs for a few
thousand timesteps.

Example (on a compute node, never the login node):
    uv run --isolated --project sota/MujocoRL/eval_env python scripts/uqd_smoke.py \\
        --preset controlled_baseline --run-dir mujoco_rl_output/uqd_smoke/baseline \\
        --generations 2 --population 3 --timesteps 1500 --final-episodes 4
"""

import argparse
import json
import os
import random
import re
import sys
import time

import numpy as np

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO_ROOT)

from src.cfg.uqd_presets import resolve_uqd_config  # noqa: E402
from src.uqd.engine import UQDEngine  # noqa: E402
from src.uqd.executors import LocalExecutor  # noqa: E402
from src.uqd.final_runner import run_final_evaluation  # noqa: E402
from src.uqd.loop import initial_generation, run_generation  # noqa: E402
from src.uqd.mujoco import BINS, DESCRIPTORS, evaluation_protocol  # noqa: E402
from src.uqd.seeds import derive_int  # noqa: E402

SEED_NETWORK = os.path.join(REPO_ROOT, "sota", "MujocoRL", "network.py")
MODELS_DIR = os.path.join(REPO_ROOT, "sota", "MujocoRL", "models")

HIDDEN_CHOICES = ([32, 32], [64, 64], [128, 128], [64], [256, 256])
LR_CHOICES = (1e-4, 3e-4, 1e-3)
NOISE_CHOICES = (0.05, 0.1, 0.2)


def mutate_gene(source_text, rng):
    """Test-only stand-in for LLM mutation: resample three hyperparameters."""
    text = re.sub(r"HIDDEN_PI = \[[^\]]*\]", f"HIDDEN_PI = {HIDDEN_CHOICES[rng.integers(len(HIDDEN_CHOICES))]}",
                  source_text, count=1)
    text = re.sub(r"learning_rate=[0-9.e-]+", f"learning_rate={LR_CHOICES[rng.integers(len(LR_CHOICES))]}",
                  text, count=1)
    text = re.sub(r"exploration_noise=[0-9.e-]+",
                  f"exploration_noise={NOISE_CHOICES[rng.integers(len(NOISE_CHOICES))]}", text, count=1)
    return text


def write_gene(gene_id, text):
    with open(os.path.join(MODELS_DIR, f"network_{gene_id}.py"), "w", encoding="utf-8") as f:
        f.write("# Generated by scripts/uqd_smoke.py (test-only random mutation, not the LLM)\n" + text)


def gene_source(gene_id):
    path = SEED_NETWORK if gene_id is None else os.path.join(MODELS_DIR, f"network_{gene_id}.py")
    with open(path, encoding="utf-8") as f:
        return f.read()


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--preset", required=True)
    parser.add_argument("--overrides", default="", help="JSON merged on top of the preset")
    parser.add_argument("--run-seed", type=int, default=0)
    parser.add_argument("--run-dir", required=True)
    parser.add_argument("--generations", type=int, default=2)
    parser.add_argument("--population", type=int, default=3)
    parser.add_argument("--timesteps", type=int, default=1500)
    parser.add_argument("--env", default="Walker2d-v5")
    parser.add_argument("--eval-max-steps", type=int, default=1000)
    parser.add_argument("--final-episodes", type=int, default=4)
    parser.add_argument("--skip-final", action="store_true")
    parser.add_argument("--aria", action="store_true", help="run the configured post-hoc ARIA stage")
    args = parser.parse_args()

    cfg = resolve_uqd_config(args.preset, args.overrides, population_size=args.population)
    protocol = evaluation_protocol(args.env, args.eval_max_steps)
    run_dir = os.path.abspath(args.run_dir)
    engine = UQDEngine(cfg, DESCRIPTORS, BINS, args.run_seed, protocol, run_dir=run_dir,
                       initial_population_size=args.population)
    engine.write_run_metadata(REPO_ROOT, extra={
        "driver": "scripts/uqd_smoke.py (test-only mutation, not the LLM)",
        "training_timesteps": args.timesteps, "generations": args.generations,
        "population": args.population})

    random.seed(engine.seeds.search_seed())
    mut_rng = np.random.default_rng(engine.seeds.search_seed())
    # Gene ids must not collide between concurrent smoke runs sharing models/.
    run_tag = f"uqdsm{args.run_seed}x{derive_int(cfg['name'], run_dir, bound=1 << 32):08x}"
    executor = LocalExecutor(REPO_ROOT, os.path.join(run_dir, "jobs"))
    train_kwargs = dict(timesteps=args.timesteps, env_id=args.env, eval_max_steps=args.eval_max_steps,
                        model_dir=os.path.join(run_dir, "models"), stats_dir=os.path.join(run_dir, "stats"))

    def make_children(parents, generation):
        kids = []
        for i, parent in enumerate(parents):
            gid = f"{run_tag}g{generation}i{i}"
            write_gene(gid, mutate_gene(gene_source(parent), mut_rng))
            kids.append(gid)
        return kids

    t0 = time.time()
    initial = make_children([None] * args.population, 0)
    snap = initial_generation(engine, executor, initial, train_kwargs)
    print(f"[gen 0] {json.dumps(snap['illusory_metrics'])}", flush=True)
    for gen in range(1, args.generations + 1):
        if engine.budget_exhausted():
            engine.finished_reason = "total_env_steps budget reached"
            break
        snap = run_generation(engine, executor, gen, make_children, train_kwargs)
        print(f"[gen {gen}] {json.dumps(snap['illusory_metrics'])} plan={snap['plan']}", flush=True)
    engine.end_generation(engine.generation)
    print(f"search finished in {time.time() - t0:.0f}s; cost: "
          f"{json.dumps(engine.ledger.summary()['search_env_steps_measured'])} env steps", flush=True)

    if not args.skip_final:
        final = run_final_evaluation(run_dir, executor, episodes=args.final_episodes)
        print("[final]", json.dumps({k: {m: v for m, v in r.items() if m != "corrected_archive"}
                                     for k, r in final["metrics"]["reports"].items()}, default=str))
    if args.aria:
        from src.uqd.aria_runner import run_aria_stage
        aria_out = run_aria_stage(run_dir, final_episodes=args.final_episodes, executor=executor)
        print("[aria]", json.dumps(aria_out["summary"], default=str))
    print("Job Done")


if __name__ == "__main__":
    main()
